#!/bin/bash
set -euo pipefail

GESTALT_DIR="${GESTALT_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
WORKSPACE="${WORKSPACE:-$(cd "$GESTALT_DIR/.." && pwd)}"
BRANCHES="$GESTALT_DIR/BRANCHES.md"
REPORT="$GESTALT_DIR/STALENESS_REPORT.md"
MANIFEST="$GESTALT_DIR/MANIFEST.md"

if [ ! -f "$BRANCHES" ]; then
    echo "No BRANCHES.md found. Run /learn or /review first."
    exit 0
fi

declare -A repo_heads=()
declare -A repo_synced=()
declare -A findings=()
has_findings=false

while IFS= read -r line; do
    if [[ "$line" =~ ^###\ (.+)$ ]]; then
        current_repo="${BASH_REMATCH[1]}"
    elif [[ "$line" =~ ^\|\ HEAD\ \|\ \`([a-f0-9]+)\` ]]; then
        repo_heads["$current_repo"]="${BASH_REMATCH[1]}"
    elif [[ "$line" =~ ^\|\ Last\ synced\ \|\ (.+)\ \| ]]; then
        repo_synced["$current_repo"]="${BASH_REMATCH[1]}"
    fi
done < "$BRANCHES"

for repo in "${!repo_heads[@]}"; do
    repo_path="$WORKSPACE/$repo"
    [ ! -d "$repo_path/.git" ] && continue

    synced_head="${repo_heads[$repo]}"
    last_synced="${repo_synced[$repo]:-unknown}"

    current_head=$(git -C "$repo_path" rev-parse HEAD 2>/dev/null || echo "unknown")
    if [ "$current_head" = "unknown" ]; then
        continue
    fi

    git -C "$repo_path" fetch --quiet 2>/dev/null || true

    if [ "$current_head" != "$synced_head" ]; then
        commit_count=$(git -C "$repo_path" rev-list "$synced_head".."$current_head" --count 2>/dev/null || echo "?")
        changed_dirs=$(git -C "$repo_path" diff "$synced_head".."$current_head" --name-only 2>/dev/null \
            | sed 's|/[^/]*$||' | sort -u | head -10 | tr '\n' ', ' | sed 's/,$//')

        if [ "$commit_count" -gt 20 ] 2>/dev/null; then
            risk="HIGH"
        elif [ "$commit_count" -gt 5 ] 2>/dev/null; then
            risk="MEDIUM"
        else
            risk="LOW"
        fi

        findings["$repo"]="$risk|$commit_count|$last_synced|$changed_dirs"
        has_findings=true
    fi
done

if [ "$has_findings" = false ]; then
    rm -f "$REPORT"
    exit 0
fi

{
    echo "# Staleness Report"
    echo ""
    echo "> Auto-generated by \`bin/check-staleness.sh\`. Do not edit manually."
    echo "> Generated: $(date +%Y-%m-%d\ %H:%M)"
    echo ""
    echo "## Git-Based Staleness"
    echo ""
    echo "| Repo | Risk | Commits Since Sync | Last Synced | Changed Directories |"
    echo "|------|------|-------------------|-------------|-------------------|"

    for repo in $(echo "${!findings[@]}" | tr ' ' '\n' | sort); do
        IFS='|' read -r risk commits synced dirs <<< "${findings[$repo]}"
        echo "| $repo | **$risk** | $commits | $synced | $dirs |"
    done

    echo ""
    echo "## Recommended Actions"
    echo ""
    for repo in $(echo "${!findings[@]}" | tr ' ' '\n' | sort); do
        IFS='|' read -r risk commits synced dirs <<< "${findings[$repo]}"
        if [ "$risk" = "HIGH" ]; then
            echo "- **$repo**: Run \`/review\` or \`/learn $repo\` — $commits commits since $synced"
        elif [ "$risk" = "MEDIUM" ]; then
            echo "- **$repo**: Consider running \`/review\` — $commits commits since $synced"
        fi
    done
} > "$REPORT"

echo "Staleness report written to $REPORT"
echo ""

high_count=0
medium_count=0
for repo in "${!findings[@]}"; do
    IFS='|' read -r risk _ _ _ <<< "${findings[$repo]}"
    [ "$risk" = "HIGH" ] && high_count=$((high_count + 1))
    [ "$risk" = "MEDIUM" ] && medium_count=$((medium_count + 1))
done

echo "Summary: $high_count HIGH, $medium_count MEDIUM risk entries"
